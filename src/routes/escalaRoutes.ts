import {Router} from 'express';
import * as c from '../controllers/escalaController';
import {authenticate,requireRoles} from '../middlewares/auth';
export const escalaRoutes=Router();
escalaRoutes.use(authenticate);
escalaRoutes.post('/turnos',requireRoles('ADMIN_PLATAFORMA'),c.criarTurno);
escalaRoutes.get('/turnos',c.listarTurnos);
escalaRoutes.get('/turnos/:id',c.detalheTurno);
escalaRoutes.patch('/turnos/:id/publicar',requireRoles('ADMIN_PLATAFORMA'),c.publicarTurno);
escalaRoutes.post('/turnos/:id/vagas',requireRoles('ADMIN_PLATAFORMA'),c.criarVaga);
escalaRoutes.get('/turnos/:id/vagas',c.listarVagas);
escalaRoutes.get('/turnos/:id/alocacoes',c.listarAlocacoes);
escalaRoutes.get('/turnos/:id/projecao',c.projecao);
escalaRoutes.post('/turnos/:id/bonus',requireRoles('ADMIN_PLATAFORMA'),c.criarBonus);
escalaRoutes.post('/turnos/:id/alteracoes',requireRoles('ADMIN_PLATAFORMA'),c.alterarEscala);
escalaRoutes.get('/alteracoes/:id/aceites',c.listarAceites);
escalaRoutes.post('/vagas/:id/candidaturas',requireRoles('ADMIN_PLATAFORMA'),c.candidatar);
escalaRoutes.post('/vagas/:id/alocacoes',requireRoles('ADMIN_PLATAFORMA'),c.alocar);
escalaRoutes.patch('/alocacoes/:id/aceite',requireRoles('ADMIN_PLATAFORMA'),c.responderAlocacao);
