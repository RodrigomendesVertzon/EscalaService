import {Request,Response,NextFunction} from 'express';
import * as s from '../services/escalaService';
import {id} from '../schemas';
import {AppError} from '../utils/AppError';
const actor=(req:Request)=>{if(!req.auth)throw new AppError(401,'TOKEN_AUSENTE','Autenticação necessária');return req.auth;};
const wrap=(fn:(req:Request)=>Promise<unknown>,status=200)=>(req:Request,res:Response,next:NextFunction)=>{Promise.resolve().then(()=>fn(req)).then(data=>res.status(status).json(data)).catch(next);};
export const criarTurno=wrap(req=>s.criarTurno(req.body,actor(req),req.correlationId),201);
export const listarTurnos=wrap(req=>s.listarTurnos(id.parse(req.query.empresaId)));
export const detalheTurno=wrap(req=>s.detalheTurno(id.parse(req.params.id)));
export const publicarTurno=wrap(req=>s.publicarTurno(id.parse(req.params.id),actor(req),req.correlationId));
export const criarVaga=wrap(req=>s.criarVaga(id.parse(req.params.id),req.body,actor(req),req.correlationId),201);
export const listarVagas=wrap(req=>s.listarVagas(id.parse(req.params.id)));
export const candidatar=wrap(req=>s.candidatar(id.parse(req.params.id),req.body,actor(req),req.correlationId),201);
export const alocar=wrap(req=>s.alocar(id.parse(req.params.id),req.body,actor(req),req.correlationId),201);
export const responderAlocacao=wrap(req=>s.responderAlocacao(id.parse(req.params.id),req.body,actor(req),req.correlationId));
export const listarAlocacoes=wrap(req=>s.listarAlocacoes(id.parse(req.params.id)));
export const criarBonus=wrap(req=>s.criarBonus(id.parse(req.params.id),req.body,actor(req),req.correlationId),201);
export const projecao=wrap(req=>s.projecao(id.parse(req.params.id)));
export const alterarEscala=wrap(req=>s.alterarEscala(id.parse(req.params.id),req.body,actor(req),req.correlationId),201);
export const listarAceites=wrap(req=>s.listarAceites(id.parse(req.params.id)));
